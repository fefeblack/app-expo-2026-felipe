-- SONORA: estrutura inicial do Supabase
-- Execute este SQL em Supabase > SQL Editor.
-- As políticas permitem que qualquer pessoa leia artigos/contribuições aprovadas,
-- mas somente usuários autenticados enviem contribuições.

create table if not exists public.contributions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  song_title text not null,
  song_artist text,
  section text not null,
  content text not null,
  source_url text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

alter table public.contributions enable row level security;

drop policy if exists "Users can submit contributions" on public.contributions;
create policy "Users can submit contributions"
on public.contributions for insert
to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Users can read approved contributions" on public.contributions;
create policy "Users can read approved contributions"
on public.contributions for select
to anon, authenticated
using (status = 'approved');

